"""Build the standalone ``MediaFix.zip`` addon package.

Mirrors ``package_gwizard_filemerge.py``. Collects the media-fix modules from
``gramps/plugins/tool`` into a flat ``MediaFix/`` addon directory inside a zip
file, rewriting ``gramps.plugins.tool.X`` absolute imports and ``.X``
relative imports to flat sibling imports so the bundle loads under Gramps'
plugin importer (which imports the tool module top-level with the addon
directory on ``sys.path``). Also embeds ``MediaFix/MediaFix.gpr.py``, any
unit tests listed in ``TEST_SOURCES`` (under ``MediaFix/tests/``), and a
gettext template ``MediaFix/po/template.pot`` generated by running xgettext
over the flattened files, so its source references match the addons-source
layout.

Each build warns about media-fix modules or tests in the tree that are not
bundled, and about lines that still reference the core tree after rewriting.
Newlines are normalized to LF so the output is identical regardless of the
checkout's line-ending setting.
"""

# -------------------------------------------------------------------------
#
# Standard Python modules
#
# -------------------------------------------------------------------------
from __future__ import annotations
import argparse
import logging
import re
import shutil
import subprocess
import tempfile
import zipfile
from pathlib import Path

LOG = logging.getLogger(__name__)

PACKAGE = "MediaFix"
GPR_FILENAME = "MediaFix.gpr.py"

# Standalone addon registration file, embedded in the bundle as
# ``MediaFix/MediaFix.gpr.py``. Keep id/toolclass/optionclass in step with
# the ``gwizardmediafix`` entry in ``gramps/plugins/tool/tools.gpr.py``.
GPR_TEMPLATE = """\
# Gramps registration file for the GWizard Media Fix tool.

from gramps.gen.plug._pluginreg import (
    TOOL,
    TOOL_DBPROC,
    TOOL_MODE_GUI,
    EXPERIMENTAL,
    EXPERT,
)
from gramps.gen.const import GRAMPS_LOCALE as glocale
from gramps.version import major_version, VERSION_TUPLE

_ = glocale.translation.gettext

if (5, 2, 0) <= VERSION_TUPLE <= (6, 2, 0):
    register(
        TOOL,
        id="gwizardmediafix",
        name=_("Media Fix"),
        description=_("Fix media references in a Gramps database."),
        version="__MEDIAFIX_VERSION__",
        gramps_target_version=major_version,
        status=EXPERIMENTAL,
        audience=EXPERT,
        fname="gwizardmediafix.py",
        authors=["Kevin White"],
        authors_email=["gocaveman@gmail.com"],
        category=TOOL_DBPROC,
        toolclass="GWizardMediaFixTool",
        optionclass="GWizardMediaFixOptions",
        tool_modes=[TOOL_MODE_GUI],
        help_url="https://gramps-project.org/wiki/index.php/Addon:MediaFix_Tool",
    )
"""

# Contents of ``MediaFix/tests/__init__.py`` inside the bundle: puts the
# addon directory on ``sys.path`` so the flat sibling imports in the tests
# resolve under ``python3 -m unittest MediaFix.tests.<module>``.
TESTS_INIT = """\
\"\"\"Make the flat MediaFix addon modules importable when running the tests.\"\"\"
import os
import sys

_ADDON_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _ADDON_DIR not in sys.path:
    sys.path.insert(0, _ADDON_DIR)
"""

# Map of archive member name -> source file relative to the repo root.
SOURCES: dict[str, str] = {
    "gwizardmediafix.py": "gramps/plugins/tool/gwizardmediafix.py",
    "gwizard_common.py": "gramps/plugins/tool/gwizard_common.py",
    "gw_fixmediareferencesdialog.py": (
        "gramps/plugins/tool/gw_fixmediareferencesdialog.py"
    ),
}

# Unit-test modules bundled into ``MediaFix/tests/``: test file name ->
# source path relative to the repo root. Add entries here when the build
# warns about an unbundled test.
TEST_SOURCES: dict[str, str] = {}

# Flat sibling module names, derived from SOURCES.
SIBLINGS: tuple[str, ...] = tuple(sorted(Path(m).stem for m in SOURCES))
_ALL = "|".join(SIBLINGS)

# Applied line by line, so line numbers never change (the translation
# template relies on that). The ``\s+import`` after each module group stops
# a name matching a longer or shorter one.
REWRITES: tuple[tuple[re.Pattern[str], str], ...] = (
    (
        re.compile(rf"from\s+gramps\.plugins\.tool\.({_ALL})\s+import\b"),
        r"from \1 import",
    ),
    # Relative imports (``from .gwizard_common import`` / ``from ..X``).
    (
        re.compile(rf"from\s+\.+({_ALL})\s+import\b"),
        r"from \1 import",
    ),
    # ``from gramps.plugins.tool import gwizard_common`` -> ``import ...``.
    (
        re.compile(rf"from\s+gramps\.plugins\.tool\s+import\s+({_ALL})\b"),
        r"import \1",
    ),
)

# Any reference to a bundled module through the core tree that survives
# rewriting (e.g. a ``mock.patch("gramps.plugins.tool.X.Gtk")`` string).
LEFTOVER = re.compile(rf"gramps\.plugins\.tool\.(?:{_ALL})\b")

# Where to look for media-fix files the bundle leaves out.
MODULE_GLOBS = (
    "gramps/plugins/tool/gwizard*.py",
    "gramps/plugins/tool/gw_*.py",
)
TEST_GLOBS = (
    "gramps/plugins/tool/test/gwizard*_test.py",
    "gramps/plugins/tool/test/gw_*_test.py",
)

# xgettext keywords, matching addons-source ``make.py init`` (``_`` / ``N_``)
# plus the other gettext helpers Gramps code commonly uses.
XGETTEXT_KEYWORDS = (
    "_",
    "N_",
    "_T_",
    "sgettext",
    "ngettext:1,2",
    "pgettext:1c,2",
)


def rewrite_imports(text: str) -> str:
    """Rewrite media-fix imports to flat sibling imports."""
    for pattern, replacement in REWRITES:
        text = pattern.sub(replacement, text)
    return text


def rewrite_imports_bytes(data: bytes) -> bytes:
    """Rewrite media-fix imports, normalizing to LF newlines."""
    lines = data.decode("utf-8").splitlines(keepends=False)
    rewritten = [rewrite_imports(line) for line in lines]
    return ("\n".join(rewritten) + "\n").encode("utf-8")


def find_leftovers(name: str, data: bytes) -> list[str]:
    """
    List lines in a rewritten member that still reference the core tree.

    :param name: Archive member name, used in the messages.
    :param data: Rewritten member bytes.
    :returns: ``"<name>:<line>: <text>"`` strings, empty when clean.
    """
    found = []
    for number, line in enumerate(data.decode("utf-8").splitlines(), start=1):
        if LEFTOVER.search(line):
            found.append(f"{name}:{number}: {line.strip()}")
    return found


def find_unbundled(repo_root: Path) -> list[str]:
    """
    List media-fix modules and tests in the tree that the bundle leaves out.

    :param repo_root: Repository root.
    :returns: Repo-relative POSIX paths not in ``SOURCES``/``TEST_SOURCES``.
    """
    listed = set(SOURCES.values()) | set(TEST_SOURCES.values())
    missing = []
    for pattern in MODULE_GLOBS + TEST_GLOBS:
        for path in sorted(repo_root.glob(pattern)):
            rel = path.relative_to(repo_root).as_posix()
            if rel not in listed and rel not in missing:
                missing.append(rel)
    return missing


def build_gpr(version: str = "0.0.1") -> bytes:
    """Render the standalone addon registration file."""
    return GPR_TEMPLATE.replace("__MEDIAFIX_VERSION__", version).encode("utf-8")


def build_translations(members: dict[str, bytes], gpr: bytes) -> bytes:
    """
    Generate ``po/template.pot`` the way addons-source ``make.py init`` does.

    The flattened members and the ``.gpr.py`` are written into a temporary
    ``MediaFix/`` directory and xgettext is run from its parent with relative
    paths, so the ``#:`` references read ``MediaFix/<file>.py:<line>`` and
    match the files actually shipped.

    :param members: Archive member name -> bytes for the flat ``.py`` files.
    :param gpr: Rendered ``MediaFix.gpr.py`` bytes.
    :returns: The ``template.pot`` content with LF newlines.
    :raises FileNotFoundError: If ``xgettext`` is not on ``PATH``.
    :raises subprocess.CalledProcessError: If xgettext fails.
    """
    xgettext = shutil.which("xgettext")
    if xgettext is None:
        raise FileNotFoundError(
            "xgettext not found on PATH; install GNU gettext "
            "(or rerun with --skip-pot to build without po/template.pot)"
        )
    with tempfile.TemporaryDirectory() as tmp:
        tmp_root = Path(tmp)
        addon_dir = tmp_root / PACKAGE
        addon_dir.mkdir()
        files = dict(members)
        files[GPR_FILENAME] = gpr
        for name, data in files.items():
            (addon_dir / name).write_bytes(data)
        inputs = [f"{PACKAGE}/{name}" for name in sorted(files)]
        output = "template.pot"
        cmd = [
            xgettext,
            "--language=Python",
            "--from-code=UTF-8",
            "--add-comments=Translators",
            f"--package-name={PACKAGE}",
            *(f"--keyword={kw}" for kw in XGETTEXT_KEYWORDS),
            "-o",
            output,
            *inputs,
        ]
        LOG.debug("Running %s", " ".join(cmd))
        subprocess.run(cmd, cwd=tmp_root, check=True)
        pot = tmp_root / output
        if not pot.is_file():
            raise FileNotFoundError("xgettext produced no template.pot")
        lines = pot.read_bytes().decode("utf-8").splitlines(keepends=False)
    return ("\n".join(lines) + "\n").encode("utf-8")


def build_zip(
    repo_root: Path, output: Path, version: str = "0.0.1", pot: bool = True
) -> Path:
    """
    Create the addon zip file.

    :returns: The path to the created zip.
    :raises FileNotFoundError: If a listed source file or xgettext is missing.
    """
    members: dict[str, bytes] = {}
    for member, source in SOURCES.items():
        path = repo_root / source
        if not path.is_file():
            raise FileNotFoundError(f"Missing source file: {path}")
        members[member] = rewrite_imports_bytes(path.read_bytes())
        LOG.debug("Added %s (%d bytes)", source, len(members[member]))

    test_members: dict[str, bytes] = {}
    for member, source in TEST_SOURCES.items():
        path = repo_root / source
        if not path.is_file():
            raise FileNotFoundError(f"Missing test source file: {path}")
        test_members[member] = rewrite_imports_bytes(path.read_bytes())
        LOG.debug("Added test %s (%d bytes)", source, len(test_members[member]))

    for rel in find_unbundled(repo_root):
        LOG.warning("Not bundled (add to SOURCES/TEST_SOURCES?): %s", rel)
    for name, data in list(members.items()) + [
        (f"tests/{n}", d) for n, d in test_members.items()
    ]:
        for leftover in find_leftovers(name, data):
            LOG.warning("Unrewritten core reference: %s", leftover)

    gpr = build_gpr(version)
    # Build the template before touching the output zip so an xgettext
    # failure leaves any previous bundle in place.
    po_template = build_translations(members, gpr) if pot else None

    output.unlink(missing_ok=True)
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(PACKAGE + "/", b"")
        archive.writestr(f"{PACKAGE}/{GPR_FILENAME}", gpr)
        for member in sorted(members):
            archive.writestr(f"{PACKAGE}/{member}", members[member])
        if test_members:
            archive.writestr(f"{PACKAGE}/tests/", b"")
            archive.writestr(f"{PACKAGE}/tests/__init__.py", TESTS_INIT.encode("utf-8"))
            for member in sorted(test_members):
                archive.writestr(f"{PACKAGE}/tests/{member}", test_members[member])
        if po_template is not None:
            archive.writestr(f"{PACKAGE}/po/", b"")
            archive.writestr(f"{PACKAGE}/po/template.pot", po_template)

    LOG.info("Wrote %s (%d bytes)", output, output.stat().st_size)
    return output


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(description="Build the MediaFix addon zip.")
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=None,
        help="Destination zip file (default: MediaFix_v<version>.zip next to script).",
    )
    parser.add_argument(
        "--version",
        dest="version_opt",
        default="0.0.1",
        help="MediaFix plugin version (default: 0.0.1).",
    )
    parser.add_argument(
        "version_pos",
        nargs="?",
        default=None,
        help="Positional version; overrides --version.",
    )
    parser.add_argument(
        "--skip-pot",
        action="store_true",
        help="Do not generate po/template.pot (use when xgettext is unavailable).",
    )
    parser.add_argument(
        "-v",
        "--verbose",
        action="store_true",
        help="Enable verbose output (debug logging).",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    """Build the bundle and report the result."""
    args = parse_args(argv)
    log_level = logging.DEBUG if args.verbose else logging.INFO
    logging.basicConfig(level=log_level, format="%(levelname)s: %(message)s")
    repo_root = Path(__file__).resolve().parent
    version = args.version_pos if args.version_pos is not None else args.version_opt
    if args.output is None:
        output = repo_root / f"MediaFix_v{version}.zip"
    else:
        output = args.output
        if not output.is_absolute():
            output = repo_root / output
    try:
        built = build_zip(repo_root, output, version, pot=not args.skip_pot)
    except FileNotFoundError as error:
        LOG.error("Build failed: %s", error)
        return 1
    except subprocess.CalledProcessError as error:
        LOG.error("Build failed: xgettext exited with %s", error.returncode)
        return 1
    print(str(built))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
