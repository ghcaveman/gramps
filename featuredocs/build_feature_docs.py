"""
build_feature_docs.py - Orchestrate Gramps feature documentation from changed_files.txt.

Lives in: featuredocs/build_feature_docs.py

Workflow:
  Step 1 (--prepare):
    Reads changed_files.txt (generated by your packaging script, excluding tests),
    extracts .gpr.py metadata and the isolated git diff against the parent branch,
    and writes:
      - featuredocs/<feature>_prompt.txt   (ready to paste into your AI assistant)
      - featuredocs/README_<feature>.md    (skeleton created if it doesn't exist yet)

  Step 2 (--build):
    Once README_<feature>.md has been populated (manually or by AI), converts it
    to MediaWiki syntax, wraps it with featuredocs/templates/header.mediawiki and
    footer.mediawiki to produce featuredocs/<feature>.mediawiki, and runs
    featuredocs/scripts/check_missing_images.py to audit screenshots.

Usage:
  1. Prepare AI prompt and starter README_<feature>.md:
       python3 featuredocs/build_feature_docs.py MyFeature --parent maintenance/gramps61 --prepare

  2. Build final .mediawiki and run missing-image check:
       python3 featuredocs/build_feature_docs.py MyFeature --build

  3. Run both steps in sequence (useful when updating an existing README_<feature>.md):
       python3 featuredocs/build_feature_docs.py MyFeature --parent feature/base-branch --prepare --build

Options:
  --filelist PATH   Path to changed_files.txt (default: ./changed_files.txt)
  --parent BRANCH   Parent git branch for isolated diff (default: maintenance/gramps61)
  --prepare         Generate AI prompt from changed_files.txt + git diff and init README_<feature>.md
  --build           Convert README_<feature>.md -> <feature>.mediawiki and run image check
"""

import argparse
import subprocess
import sys
from pathlib import Path

# Resolve paths relative to featuredocs/
FEATUREDOCS_DIR = Path(__file__).resolve().parent
REPO_ROOT = FEATUREDOCS_DIR.parent
TEMPLATES_DIR = FEATUREDOCS_DIR / "templates"
SCRIPTS_DIR = FEATUREDOCS_DIR / "scripts"
IMAGES_DIR = FEATUREDOCS_DIR / "images"


def read_filelist(filelist_path: Path) -> list[Path]:
    """Read non-empty, non-comment relative paths from changed_files.txt."""
    if not filelist_path.is_file():
        print(f"Error: filelist not found at {filelist_path}", file=sys.stderr)
        sys.exit(1)

    files = []
    for raw_line in filelist_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        files.append(Path(line))
    return files


def get_git_diff(parent_branch: str, target_files: list[Path]) -> str:
    """Run git diff against parent_branch scoped strictly to files in changed_files.txt."""
    existing_paths = [str(p) for p in target_files if (REPO_ROOT / p).exists()]
    if not existing_paths:
        return "(No matching tracked files found on disk for git diff.)"

    cmd = ["git", "diff", f"{parent_branch}...HEAD", "--"] + existing_paths
    try:
        # Use UTF‑8 decoding for git output to avoid locale‑dependent decode errors.
        result = subprocess.run(
            cmd,
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            encoding="utf-8",
            check=False,
        )
        if result.returncode != 0:
            return f"(git diff warning: {result.stderr.strip()})"
        return (
            result.stdout.strip() or "(No diff against parent branch for listed files.)"
        )
    except FileNotFoundError:
        return "(git executable not found in PATH.)"


def collect_gpr_contents(target_files: list[Path]) -> str:
    """Extract full contents of any .gpr.py registration files listed in changed_files.txt."""
    gpr_blocks = []
    for rel_path in target_files:
        if rel_path.name.endswith(".gpr.py"):
            full_path = REPO_ROOT / rel_path
            if full_path.is_file():
                content = full_path.read_text(encoding="utf-8")
                gpr_blocks.append(f"--- {rel_path.as_posix()} ---\n{content}")
    return (
        "\n\n".join(gpr_blocks)
        if gpr_blocks
        else "(No .gpr.py file found in changed_files.txt)"
    )


def prepare_docs(feature_name: str, filelist_path: Path, parent_branch: str) -> None:
    """Generate the AI prompt file and initialize README_<feature>.md if missing."""
    IMAGES_DIR.mkdir(parents=True, exist_ok=True)
    target_files = read_filelist(filelist_path)

    file_list_str = "\n".join(f"- {p.as_posix()}" for p in target_files)
    gpr_text = collect_gpr_contents(target_files)
    diff_text = get_git_diff(parent_branch, target_files)

    prompt_path = FEATUREDOCS_DIR / f"{feature_name}_prompt.txt"
    readme_path = FEATUREDOCS_DIR / f"README_{feature_name}.md"

    prompt_content = f"""You are a technical documentation writer for the Gramps Genealogy Software Wiki.
Write a clear, end-user Markdown manual for the feature '{feature_name}'.
Save your output into: {readme_path.as_posix()}

### Strict Rules:
1. Base all UI labels, menu paths, checkboxes, and behavior strictly on the provided .gpr.py metadata and git diff.
2. Write for genealogists (end-users) using standard Gramps terminology (Gramplet, Filter, Active Person, Family Tree).
3. Do NOT include top-level title banners, infobox tables, Prerequisites, Issues, or Categories (those are added automatically by header.mediawiki and footer.mediawiki).
4. Include these Markdown sections using `##` headings:
   - `## Overview` (brief summary of what this feature accomplishes)
   - `## Usage` (numbered steps starting from the exact Gramps menu or Gramplet bar)
   - `## Configure Options` (bulleted list matching every GUI control/option in the code)
   - `## Features` (bulleted list of key capabilities)
5. Where screenshots are helpful, insert Markdown image tags using this exact collision-proof naming format:
   `![Caption describing what to capture](images/{feature_name}-<short-name>.png)`
6. Do not invent menu paths or options not present in the diff. If a menu path is inherited and unclear, mark it `[VERIFY MENU PATH]`.

### Feature Files (from {filelist_path.name}):
{file_list_str}

### Plugin Registration Metadata (.gpr.py):
{gpr_text}

### Isolated Feature Diff (against {parent_branch}):
{diff_text}
"""
    prompt_path.write_text(prompt_content, encoding="utf-8")
    print(f"[PREPARE] Wrote AI prompt to: {prompt_path}")

    if not readme_path.exists():
        starter_md = f"""## Overview

Describe what **{feature_name}** does and what genealogical workflow it improves.

![{feature_name} main dialog](images/{feature_name}-main.png)

## Usage

1. Open Gramps and navigate to **[VERIFY MENU PATH]**.
2. Configure your desired options and click **OK**.

## Configure Options

* **Option 1**: Description of option 1.

## Features

* Key feature 1.
"""
        readme_path.write_text(starter_md, encoding="utf-8")
        print(f"[PREPARE] Created starter Markdown: {readme_path}")
    else:
        print(f"[PREPARE] Kept existing Markdown: {readme_path}")

    print("\nNext step:")
    print(
        f"  1. Feed {prompt_path.name} to your AI assistant and save the result into {readme_path.name}."
    )
    print(
        f"  2. Run: python3 featuredocs/build_feature_docs.py {feature_name} --build\n"
    )


def build_wiki_and_audit(feature_name: str) -> int:
    """Convert README_<feature>.md -> <feature>.mediawiki with templates and audit images."""
    readme_path = FEATUREDOCS_DIR / f"README_{feature_name}.md"
    mediawiki_path = FEATUREDOCS_DIR / f"{feature_name}.mediawiki"
    header_path = TEMPLATES_DIR / "header.mediawiki"
    footer_path = TEMPLATES_DIR / "footer.mediawiki"

    md_converter = SCRIPTS_DIR / "md_to_mediawiki.py"
    image_checker = SCRIPTS_DIR / "check_missing_images.py"

    if not readme_path.is_file():
        print(
            f"Error: {readme_path} not found. Run with --prepare first.",
            file=sys.stderr,
        )
        return 1

    # Import md_to_mediawiki directly from featuredocs/scripts/
    sys.path.insert(0, str(SCRIPTS_DIR))
    try:
        from md_to_mediawiki import md_to_mediawiki
    except ImportError as exc:
        print(
            f"Error: Could not import md_to_mediawiki.py from {SCRIPTS_DIR}: {exc}",
            file=sys.stderr,
        )
        return 1

    header_text = (
        header_path.read_text(encoding="utf-8") + "\n" if header_path.is_file() else ""
    )
    footer_text = (
        "\n" + footer_path.read_text(encoding="utf-8") if footer_path.is_file() else ""
    )

    if not header_text:
        print(f"Warning: {header_path} not found; building without header template.")
    if not footer_text:
        print(f"Warning: {footer_path} not found; building without footer template.")

    body_mediawiki = md_to_mediawiki(readme_path.read_text(encoding="utf-8"))
    final_mediawiki = header_text + body_mediawiki + footer_text

    # Write MediaWiki output using UTF‑8 bytes to avoid console encoding issues.
    mediawiki_path.write_bytes(final_mediawiki.encode("utf-8", errors="ignore"))
    print(f"[BUILD] Generated MediaWiki file: {mediawiki_path}")

    # Run featuredocs/scripts/check_missing_images.py on the assembled .mediawiki file
    if not image_checker.is_file():
        print(
            f"Error: Missing image checker script at {image_checker}", file=sys.stderr
        )
        return 1

    print("[AUDIT] Running missing-image check...")
    # Capture the stdout of the image‑audit script so we can both display it
    # to the user *and* write it to a persistent log file.  This makes it easy
    # to reference the audit later (e.g. in CI or when filing a bug).
    # Run the image‑audit script and capture its output as UTF‑8 text.  The default
    # ``text=True`` uses the system locale encoding (cp1252 on Windows), which can
    # raise ``UnicodeDecodeError`` when the script emits non‑ASCII characters.
    # Explicitly request UTF‑8 decoding to avoid this issue.
    audit_proc = subprocess.run(
        [
            sys.executable,
            str(image_checker),
            str(mediawiki_path),
            "--images-dir",
            str(IMAGES_DIR),
        ],
        capture_output=True,  # capture stdout / stderr as strings
        text=True,
        encoding="utf-8",
        check=False,
    )

    # Write the full audit report to a side‑car file next to the generated
    # MediaWiki document.  The filename follows the convention
    #   <feature>_image_audit.txt
    audit_log_path = FEATUREDOCS_DIR / f"{feature_name}_image_audit.txt"
    try:
        # Write using UTF‑8 and ignore characters that cannot be encoded by the
        # underlying Windows console code page.  This prevents a ``UnicodeEncodeError``
        # when the audit output contains typographic dashes or other Unicode symbols.
        # Fallback to binary write to avoid encoding issues on Windows.
        audit_log_path.write_bytes(audit_proc.stdout.encode("utf-8", errors="ignore"))
        print(f"[AUDIT] Image‑audit written to: {audit_log_path}")
    except Exception:
        # Silently ignore write failures on Windows consoles where the default
        # encoding cannot represent certain Unicode characters (e.g., en‑dash).
        # The audit log is non‑essential for CI; the user can regenerate it if
        # needed.
        pass

    # Echo the audit output so the console still shows the familiar table.
    sys.stdout.write(audit_proc.stdout)

    # Propagate the original exit status (0 = all images present).
    # The image‑audit script returns a non‑zero code when images are missing.
    # For documentation builds we do not want this to abort the overall
    # process, so treat any non‑zero result as a warning and return success.
    return 0


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Orchestrate Gramps feature Markdown generation, MediaWiki conversion, and image auditing."
    )
    parser.add_argument(
        "feature",
        help="Feature name slug (e.g., MyFeature). Produces README_<feature>.md and <feature>.mediawiki",
    )
    parser.add_argument(
        "--filelist",
        type=Path,
        default=Path("changed_files.txt"),
        help="Path to changed_files.txt generated by your packaging script (default: ./changed_files.txt)",
    )
    parser.add_argument(
        "--parent",
        default="maintenance/gramps61",
        help="Parent git branch to diff against (default: maintenance/gramps61)",
    )
    parser.add_argument(
        "--prepare",
        action="store_true",
        help="Read changed_files.txt + git diff to build prompt.txt and starter README.md",
    )
    parser.add_argument(
        "--build",
        action="store_true",
        help="Convert README_.md with templates into .mediawiki and check missing images",
    )
    args = parser.parse_args()
    # Ensure at least one action is specified
    if not args.prepare and not args.build:
        parser.print_help()
        print(
            "\nError: Specify at least one action: --prepare and/or --build",
            file=sys.stderr,
        )
        sys.exit(1)

    # Execute the requested actions and report success/failure
    if args.prepare:
        try:
            prepare_docs(args.feature, args.filelist, args.parent)
            print("[PREPARE] Completed successfully.")
        except Exception as exc:  # pragma: no cover
            print(f"[PREPARE] Failed: {exc}", file=sys.stderr)
            sys.exit(1)

    if args.build:
        exit_code = build_wiki_and_audit(args.feature)
        if exit_code == 0:
            print("[BUILD] Completed successfully.")
        else:
            print(f"[BUILD] Failed with exit code {exit_code}", file=sys.stderr)
        sys.exit(exit_code)


# Standard Python entry point guard
if __name__ == "__main__":
    main()
