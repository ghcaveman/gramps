# Fixture tree bundled into ``GWizardFileMerge/tests/data/`` inside the zip,
# relative to the repo root. The bundled ``GWizardSourceMediaMergeTest``
# resolves it as ``os.path.join(os.path.dirname(__file__), "data")`` next to
# ``gwizard_test.py``, and the GEDCOM's relative ``FILE media/...`` paths
# resolve against the ``.ged`` file's own directory, so the whole tree is
# copied across preserving its layout. Files are copied verbatim (no import
# rewriting): text files only get newline normalization, and the ``.png``
# images are byte-for-byte copies since import rewriting assumes UTF-8 text.
TEST_DATA_DIR = "gramps/gen/gwizard/test/data"

# GWizard sibling modules bundled flat in the addon directory. Gramps loads
# the tool module top-level (``__import__("gwizardmerge")`` with the addon
# directory on ``sys.path``), so intra-bundle imports must be flat as well:
# ``gramps.gen.gwizard.X`` / ``gramps.gui.gwizard.X`` /
# ``gramps.plugins.tool.gwizardmerge`` absolute imports and ``.X`` relative
# imports all become ``X`` sibling imports. Derived from ``SOURCES`` so a
# module added there is rewritten automatically.
SIBLINGS: tuple[str, ...] = tuple(sorted(Path(m).stem for m in SOURCES))

_ALL = "|".join(SIBLINGS)
# The launcher is excluded from the generic absolute rule: gwizardmerge.py
# has ``try: from gwizardlauncher import ...`` with a source-tree fallback
# ``except ImportError: from gramps.gui.gwizard.gwizardlauncher import (``.
# Single-line launcher imports are still rewritten by the dedicated rule
# below; only the parenthesised fallback is left alone.
_NOT_LAUNCHER = "|".join(m for m in SIBLINGS if m != "gwizardlauncher")

# Patterns are applied line by line, so line numbers never change (the
# translation template relies on that). The ``\s+import`` after each module
# group keeps ``gwizard_base`` from matching a shorter name or vice versa.
REWRITES: tuple[tuple[re.Pattern[str], str], ...] = (
    (
        re.compile(rf"from\s+gramps\.(?:gen|gui)\.gwizard\.({_NOT_LAUNCHER})\s+import\b"),
        r"from \1 import",
    ),
    (
        re.compile(r"from\s+gramps\.gui\.gwizard\.gwizardlauncher\s+import\b(?!\s*\()"),
        "from gwizardlauncher import",
    ),
    (
        re.compile(r"from\s+gramps\.plugins\.tool\.gwizardmerge\s+import\b"),
        "from gwizardmerge import",
    ),
    # Relative imports: one or more leading dots flatten to a sibling import
    # (``from .gwizard_base import`` / ``from ..gwizard_base import``).
    (
        re.compile(rf"from\s+\.+({_ALL})\s+import\b"),
        r"from \1 import",
    ),
    # Module-from-package imports (``from gramps.gui.gwizard import
    # gwizardmergedialog``) become a bare ``import <module>`` sibling import.
    (
        re.compile(
            rf"from\s+gramps\.(?:(?:gen|gui)\.gwizard|plugins\.tool)\s+import\s+"
            rf"({_ALL})\b"
        ),
        r"import \1",
    ),
)

# Any GWizard reference still left after rewriting (for example a
# ``mock.patch("gramps.gui.gwizard.X.Gtk")`` string, or an import style the
# patterns above don't know) would point at the core tree inside the addon.
LEFTOVER = re.compile(
    r"gramps\.(?:gen|gui)\.gwizard\b|gramps\.plugins\.tool\.gwizardmerge\b"
)
# Known, intentional leftover: the source-tree fallback in gwizardmerge.py.
LEFTOVER_ALLOWED = re.compile(
    r"^\s*from\s+gramps\.gui\.gwizard\.gwizardlauncher\s+import\s*\(\s*$"
)

# Where to look for GWizard files that exist in the tree but are not listed
# in SOURCES / TEST_SOURCES (reported as warnings so nothing is dropped
# silently).
MODULE_GLOBS = (
    "gramps/gen/gwizard/*.py",
    "gramps/gui/gwizard/*.py",
    "gramps/plugins/tool/gwizard*.py",
)
TEST_GLOBS = (
    "gramps/gen/gwizard/test/*_test.py",
    "gramps/gui/gwizard/test/*_test.py",
    "gramps/plugins/tool/test/gwizard*_test.py",
)


def rewrite_imports(text: str) -> str:
    """Rewrite GWizard imports to flat sibling imports."""
    for pattern, replacement in REWRITES:
        text = pattern.sub(replacement, text)
    return text


def rewrite_imports_bytes(data: bytes) -> bytes:
    """Rewrite GWizard imports, normalizing to LF newlines."""
    lines = data.decode("utf-8").splitlines(keepends=False)
    rewritten = [rewrite_imports(line) for line in lines]
    return ("\n".join(rewritten) + "\n").encode("utf-8")


def find_leftovers(name: str, data: bytes) -> list[str]:
    """
    List lines in a rewritten member that still reference the core tree.

    :param name: Archive member name, used in the messages.
    :param data: Rewritten member bytes.
    :returns: ``"<name>:<line>: <text>"`` strings, empty when clean.
    """
    found = []
    for number, line in enumerate(data.decode("utf-8").splitlines(), start=1):
        if LEFTOVER.search(line) and not LEFTOVER_ALLOWED.match(line):
            found.append(f"{name}:{number}: {line.strip()}")
    return found


def find_unbundled(repo_root: Path) -> list[str]:
    """
    List GWizard modules and tests in the tree that the bundle leaves out.

    :param repo_root: Repository root.
    :returns: Repo-relative POSIX paths not in ``SOURCES``/``TEST_SOURCES``.
    """
    listed = set(SOURCES.values()) | set(TEST_SOURCES.values())
    missing = []
    for pattern in MODULE_GLOBS + TEST_GLOBS:
        for path in sorted(repo_root.glob(pattern)):
            rel = path.relative_to(repo_root).as_posix()
            if path.name == "__init__.py" or rel in listed:
                continue
            missing.append(rel)
    return missing


def build_gpr(version: str = "0.0.1") -> bytes:
    """Render the standalone addon registration file."""
    return GPR_TEMPLATE.replace("__GWIZARD_VERSION__", version).encode("utf-8")


def build_test_data(repo_root: Path) -> dict[str, bytes]:
    """
    Collect the test fixture tree for ``tests/data/`` in the bundle.

    :param repo_root: Repository root holding the fixture tree.
    :returns: Map of archive-relative POSIX path to file bytes.
    :raises FileNotFoundError: If the fixture tree or GEDCOM fixture is
        missing from the repository.
    """
    data_root = repo_root / TEST_DATA_DIR
    if not data_root.is_dir():
        raise FileNotFoundError(f"Missing test data directory: {data_root}")
    ged_fixture = data_root / "gwizard_mergefrom_sources.ged"
    if not ged_fixture.is_file():
        raise FileNotFoundError(f"Missing test fixture file: {ged_fixture}")
    members: dict[str, bytes] = {}
    for path in sorted(data_root.rglob("*")):
        if not path.is_file():
            continue
        member = path.relative_to(data_root).as_posix()
        raw = path.read_bytes()
        if path.suffix.lower() == ".png":
            # Binary image: byte-for-byte copy, import rewriting would
            # corrupt it (rewrite_imports_bytes decodes UTF-8 text).
            members[member] = raw
        else:
            # Text fixture (GEDCOM, generator script): normalize newlines
            # like the code members so the bundle is deterministic.
            lines = raw.decode("utf-8").splitlines(keepends=False)
            members[member] = ("\n".join(lines) + "\n").encode("utf-8")
        LOG.debug("Added data %s (%d bytes)", member, len(members[member]))
    return members


# xgettext keywords, matching the Gramps addons-source ``make.py init`` step
# (``_`` / ``N_``) plus the other gettext helpers Gramps code commonly uses.
XGETTEXT_KEYWORDS = (
    "_",
    "N_",
    "_T_",
    "sgettext",
    "ngettext:1,2",
    "pgettext:1c,2",
)


def build_translations(members: dict[str, bytes], gpr: bytes) -> bytes:
    """
    Generate ``po/template.pot`` the way addons-source ``make.py init`` does.

    The source tree is spread across ``gramps/gen``, ``gramps/gui`` and
    ``gramps/plugins``, so running xgettext there records the wrong paths.
    Instead the already-flattened bundle members (and the generated ``.gpr.py``)
    are written into a temporary ``GWizardFileMerge/`` directory and xgettext
    is run from its parent with relative paths, exactly like::

        xgettext --language=Python --keyword=_ --keyword=N_ --from-code=UTF-8 \
            -o GWizardFileMerge/po/template.pot GWizardFileMerge/*.py

    in addons-source. The ``#:`` references therefore read
    ``GWizardFileMerge/<file>.py:<line>`` and, because import rewriting is
    line-for-line, the line numbers match the files actually shipped.

    :param members: Archive member name -> bytes for the flat ``.py`` files.
    :param gpr: Rendered ``GWizardFileMerge.gpr.py`` bytes.
    :returns: The ``template.pot`` content with LF newlines.
    :raises FileNotFoundError: If ``xgettext`` is not on ``PATH``.
    :raises subprocess.CalledProcessError: If xgettext fails.
    """
    xgettext = shutil.which("xgettext")
    if xgettext is None:
        raise FileNotFoundError(
            "xgettext not found on PATH; install GNU gettext "
            "(or rerun with --skip-pot to build without po/template.pot)"
        )
    with tempfile.TemporaryDirectory() as tmp:
        tmp_root = Path(tmp)
        addon_dir = tmp_root / PACKAGE
        addon_dir.mkdir()
        files = dict(members)
        files[GPR_FILENAME] = gpr
        for name, data in files.items():
            (addon_dir / name).write_bytes(data)
        # Relative, forward-slash paths so the .pot is identical on Windows
        # and POSIX; sorted for a deterministic entry order.
        inputs = [f"{PACKAGE}/{name}" for name in sorted(files)]
        output = "template.pot"
        cmd = [
            xgettext,
            "--language=Python",
            "--from-code=UTF-8",
            "--add-comments=Translators",
            f"--package-name={PACKAGE}",
            *(f"--keyword={kw}" for kw in XGETTEXT_KEYWORDS),
            "-o",
            output,
            *inputs,
        ]
        LOG.debug("Running %s", " ".join(cmd))
        subprocess.run(cmd, cwd=tmp_root, check=True)
        pot = tmp_root / output
        if not pot.is_file():
            # xgettext writes nothing when no strings are found.
            raise FileNotFoundError("xgettext produced no template.pot")
        lines = pot.read_bytes().decode("utf-8").splitlines(keepends=False)
    return ("\n".join(lines) + "\n").encode("utf-8")


def build_zip(
    repo_root: Path, output: Path, version: str = "0.0.1", pot: bool = True
) -> Path:
    """Build the ``GWizardFileMerge.zip`` bundle next to this script."""
    members: dict[str, bytes] = {}
    for member, source in SOURCES.items():
        path = repo_root / source
        if not path.is_file():
            raise FileNotFoundError(f"Missing source file: {path}")
        text = path.read_bytes()
        members[member] = rewrite_imports_bytes(text)
        LOG.debug("Added %s (%d bytes)", source, len(members[member]))

    test_members: dict[str, bytes] = {}
    for member, source in TEST_SOURCES.items():
        path = repo_root / source
        if not path.is_file():
            raise FileNotFoundError(f"Missing test source file: {path}")
        text = path.read_bytes()
        test_members[member] = rewrite_imports_bytes(text)
        LOG.debug("Added test %s (%d bytes)", source, len(test_members[member]))

    data_members = build_test_data(repo_root)

    for rel in find_unbundled(repo_root):
        LOG.warning("Not bundled (add to SOURCES/TEST_SOURCES?): %s", rel)
    for name, data in list(members.items()) + [
        (f"tests/{n}", d) for n, d in test_members.items()
    ]:
        for leftover in find_leftovers(name, data):
            LOG.warning("Unrewritten core reference: %s", leftover)

    gpr = build_gpr(version)
    # Build the translation template before touching the output zip so an
    # xgettext failure leaves any previous bundle in place.
    po_template = build_translations(members, gpr) if pot else None

    output.unlink(missing_ok=True)
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(PACKAGE + "/", b"")
        archive.writestr(f"{PACKAGE}/{GPR_FILENAME}", gpr)
        for member in sorted(members):
            archive.writestr(f"{PACKAGE}/{member}", members[member])
        if test_members:
            archive.writestr(PACKAGE + "/tests/", b"")
            archive.writestr(PACKAGE + "/tests/__init__.py", TESTS_INIT.encode("utf-8"))
            for member in sorted(test_members):
                archive.writestr(f"{PACKAGE}/tests/{member}", test_members[member])
        if data_members:
            archive.writestr(f"{PACKAGE}/tests/data/", b"")
            for member in sorted(data_members):
                archive.writestr(f"{PACKAGE}/tests/data/{member}", data_members[member])

        if po_template is not None:
            archive.writestr(f"{PACKAGE}/po/", b"")
            archive.writestr(f"{PACKAGE}/po/template.pot", po_template)

    LOG.info("Wrote %s (%d bytes)", output, output.stat().st_size)
    return output


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description="Build the standalone GWizardFileMerge.zip addon package."
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=None,
        help="Destination zip file (default: GWizardFileMerge_v<version>.zip next to the script, where <version> is the plugin version).",
    )
    parser.add_argument(
        "--gramps-target",
        default=DEFAULT_GRAMPS_TARGET,
        help=(
            "Accepted for compatibility; the bundled registration file now "
            "uses Gramps' dynamic major_version with a VERSION_TUPLE gate, "
            f"so this value (default: {DEFAULT_GRAMPS_TARGET}) is ignored."
        ),
    )
    parser.add_argument(
        "--version",
        dest="version_opt",
        default="0.0.1",
        help="GWizard plugin version for the registration file (default: 0.0.1).",
    )
    parser.add_argument(
        "version_pos",
        nargs="?",
        default=None,
        help="GWizard plugin version for the registration file (default: 0.0.1), "
        "alternative to --version.",
    )
    parser.add_argument(
        "--skip-pot",
        action="store_true",
        help="Do not generate po/template.pot (use when xgettext is unavailable).",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    """Build the bundle and report the result."""
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    args = parse_args(argv)
    repo_root = Path(__file__).resolve().parent
    # Bare positional version takes precedence over --version; both default to
    # "0.0.1" when neither is supplied.
    version = args.version_pos if args.version_pos is not None else args.version_opt
    # Default output name embeds the plugin version: GWizardFileMerge_v<version>.zip.
    if args.output is None:
        output = repo_root / f"GWizardFileMerge_v{version}.zip"
    else:
        output = args.output
        if not output.is_absolute():
            output = repo_root / output
    try:
        built = build_zip(repo_root, output, version=version, pot=not args.skip_pot)
    except FileNotFoundError as error:
        LOG.error("%s", error)
        return 1
    except subprocess.CalledProcessError as error:
        LOG.error("xgettext failed (exit %s)", error.returncode)
        return 1
    print(str(built))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
